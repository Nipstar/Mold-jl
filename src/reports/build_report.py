"""Build the JobsLocked North Florida (jl-mold-fl) prospecting report.

Reads data/pipeline.db (maps_companies table), renders a branded summary
HTML page + PDF, and writes the two outreach CSV exports. Output lands in
geo-prospecting/claim-site/dist/report/jl-mold-fl/ — the shared dist tree
used for every Antek Automation report deploy (project antek-claim).

Usage:
    uv run python src/reports/build_report.py
"""
from __future__ import annotations

import csv
import sqlite3
import sys
