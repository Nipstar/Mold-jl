def main() -> None:
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    conn = sqlite3.connect(DB_PATH)
    rows = fetch_rows(conn)

    n_full = write_full_csv(rows, OUT_DIR / "jl-mold-fl-full.csv")
    n_outreach = write_outreach_csv(rows, OUT_DIR / "jl-mold-fl-outreach.csv")
    stats = build_stats(rows)
    conn.close()

    html = Template(TEMPLATE).render(
        stats=stats,
        seg_short=SEGMENT_SHORT,
        seg_label=SEGMENT_LABEL,
        brand=brand,
        font_face=brand.font_face_css(),
        base_css=brand.base_css(),
    )
    (OUT_DIR / "index.html").write_text(html, encoding="utf-8")

    # PDF of the summary page only (not raw data tables' full CSVs).
    from weasyprint import HTML
    HTML(string=html, base_url=str(OUT_DIR)).write_pdf(str(OUT_DIR / "jl-mold-fl-summary.pdf"))

    print(f"Full CSV: {n_full} rows")
    print(f"Outreach CSV: {n_outreach} rows")
    print(f"Wrote {OUT_DIR}/index.html, jl-mold-fl-full.csv, jl-mold-fl-outreach.csv, jl-mold-fl-summary.pdf")


if __name__ == "__main__":
    main()
